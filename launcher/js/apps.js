/* ============================================================
   apps.js — enumerate installed Tizen apps and launch them.
   Works on the TV (uses window.tizen) and in a desktop browser
   (falls back to DEMO_APPS so you can preview the UI on your PC).
   ============================================================ */
(function (global) {
    "use strict";

    var MY_APP_ID = "APLauncher.Home";

    /* Apps you told us you actually use — pinned to the front, in this order.
       TizenTube is recognised by its name (see isTizenTube) and always comes first.
       9Ur5IzDKqV.TizenYouTube is Samsung's own YouTube app, not TizenTube. */
    var FAVORITES = [
        "AquaPlay02.AquaPlay",              // AquaPlay: its widgets show on the dock
        "6YLB5zo9te.HotIptv",               // Hot IPTV
        "org.apps2samsung.overscan",        // Overscan (replaces Samsung Internet when it is installed)
        "org.tizen.browser"                 // Samsung Internet
    ];
    var OVERSCAN = "org.apps2samsung.overscan";

    /* Nicer names + accent colours for known apps. Everything else
       falls back to its Tizen name + a neutral accent. */
    var TIZENTUBE = { name: "TizenTube", accent: "#1fb6e6", eyebrow: "VIDEO", bg: "images/bg-tizentube.jpg", tile: "images/tile-tizentube.png", bgBlur: "images/blur/tizentube.jpg", live: "youtube" };
    /* TizenTube: by its name (TizenTube, TizenTube Cobalt…) or its package xvvl3S1TT1. */
    function isTizenTube(id, name) { return /tizen ?tube/i.test(String(name || "")) || /^xvvl3S1TT1\./.test(id); }
    var META = {
        "AquaPlay02.AquaPlay":            { eyebrow: "TELEVISION", live: "trending" },
        "xvvl3S1bvH.TizenBrewStandalone": { name: "TizenBrew",  accent: "#1fb6e6", eyebrow: "APPS", bg: "images/bg-tizenbrew.jpg", tile: "images/tile-tizenbrew.png", bgBlur: "images/blur/tizenbrew.jpg", live: "youtube" },
        "6YLB5zo9te.HotIptv":             { name: "Hot IPTV",   accent: "#ff7a1a", eyebrow: "TELEVISION",   bg: "images/bg-hotiptv.jpg", tile: "images/tile-hotiptv.png", bgBlur: "images/blur/hotiptv.jpg", live: "trending" },
        "org.apps2samsung.overscan":      { name: "Overscan",   accent: "#2b6fff", eyebrow: "BROWSER" },
        "org.tizen.browser":              { name: "Internet",   accent: "#2b6fff", eyebrow: "BROWSER",      bg: "images/bg-internet.jpg", tile: "images/tile-internet.png", bgBlur: "images/blur/internet.jpg" },
        "org.tizen.browser.wrt":          { name: "Internet",   accent: "#2b6fff", eyebrow: "BROWSER",      bg: "images/bg-internet.jpg", tile: "images/tile-internet.png" }
    };

    /* Catalogue of common apps (catalog.js, generated by tools/art).
       Recognised by Tizen id, else by name: the ids of
       Samsung apps vary by country, their names don't. */
    var CAT_BY_ID = {}, CAT_BY_NAME = [], CAT_BY_KEY = {};
    (global.APL_CATALOG || []).forEach(function (c) {
        CAT_BY_KEY[c.key] = c;
        (c.ids || []).forEach(function (id) { CAT_BY_ID[id] = c; });
        (c.match || []).forEach(function (re) {
            try { CAT_BY_NAME.push({ re: new RegExp(re, "i"), c: c }); } catch (e) {}
        });
    });

    var VETRO = { name: "Vetro", accent: "#3b6fd8", eyebrow: "SYSTEM" };
    var STORE = { name: "App Store", accent: "#1c6ef2", eyebrow: "APPS" };
    // Samsung's own store ids only: a third-party app whose id ends in ".Store" (Apps2Samsung's
    // TV-Store, A2STVStore.Store) is an app of its own, not a second App Store tile to drop.
    var STORE_ID = /^com\.samsung\.[\w.]*\.store$|samsungapps|^org\.volt\.apps/i;

    function lookup(id, name) {
        if (isTizenTube(id, name)) return TIZENTUBE;
        if (META[id]) return META[id];            // favourites: always take priority
        if (/^vetrotvapp/i.test(id) || /^vetro$/i.test(String(name || "").trim())) return CAT_BY_KEY.vetro || VETRO;
        if (STORE_ID.test(id)) return CAT_BY_KEY.appstore || STORE;
        if (CAT_BY_ID[id]) return CAT_BY_ID[id];
        var n = String(name || "").trim();
        for (var i = 0; i < CAT_BY_NAME.length; i++) {
            if (CAT_BY_NAME[i].re.test(n)) return CAT_BY_NAME[i].c;
        }
        return {};
    }

    /* Hide known system/placeholder entries even if they report show=true. */
    var BLOCKLIST = {};
    [MY_APP_ID].forEach(function (id) { BLOCKLIST[id] = true; });

    /* Only REAL applications: not Samsung's services, plugins and
       internal screens (Channel-list, SAFCommonPlugin, Setting…). */
    var SYSTEM_ID = /^(com\.samsung\.|org\.tizen\.|com\.tizen\.|tizen\.|dir\.|org\.volt\.|samsung\.)/i;
    var TECH_NAME = /plugin|provider|service|display|daemon|agent|widget|^setting$|channel-?list|multifunction/i;
    function isRealApp(id, name) {
        if (FAVORITES.indexOf(id) !== -1 || isTizenTube(id, name)) return true;
        if (/^org\.tizen\.browser/.test(id)) return true;
        if (/^vetrotvapp/i.test(id) || /^vetro$/i.test(String(name || "").trim())) return true;
        if (STORE_ID.test(id)) return true;                                // Samsung App Store
        var n = String(name || "").trim();
        for (var k = 0; k < CAT_BY_NAME.length; k++) {                     // apps known to the catalogue
            var c = CAT_BY_NAME[k].c;
            if (!CAT_BY_NAME[k].re.test(n)) continue;
            if (c.hide) return false;                                      // SmartThings: never
            if (c.system || !SYSTEM_ID.test(id)) return true;              // Samsung TV Plus: a Samsung app to keep
        }
        if (SYSTEM_ID.test(id)) return false;
        if (TECH_NAME.test(String(name || ""))) return false;
        if (CAT_BY_ID[id]) return true;
        if (/^[A-Za-z0-9]{10}\.[A-Za-z0-9_-]+$/.test(id)) return true;   // Store apps and installed apps
        if (/^\d{9,14}$/.test(id)) return true;                         // Samsung apps from the Store (Netflix…)
        return false;
    }

    /* Demo set used only when window.tizen is absent (PC preview). */
    var DEMO_APPS = [
        { id: "xvvl3S1TT1.TizenTubeStandalone", name: "TizenTube", icon: null },
        { id: "xvvl3S1bvH.TizenBrewStandalone", name: "TizenBrew", icon: null },
        { id: "6YLB5zo9te.HotIptv",             name: "Hot IPTV",  icon: null },
        { id: "org.tizen.browser",              name: "Internet",  icon: null },
        // Examples for the PC preview
        { id: "IkWsFHtOY9.Stremio",       name: "Stremio",     icon: null },
        { id: "kIciSQlYEM.plex",          name: "Plex",        icon: null },
        // Common Samsung apps (recognised by their name)
        { id: "demo.netflix",   name: "Netflix",          icon: null },
        { id: "demo.prime",     name: "Prime Video",      icon: null },
        { id: "demo.youtube",   name: "YouTube",          icon: null },
        { id: "demo.disney",    name: "Disney+",          icon: null },
        { id: "demo.appletv",   name: "Apple TV",         icon: null },
        { id: "demo.spotify",   name: "Spotify",          icon: null },
        { id: "demo.tvplus",    name: "Samsung TV Plus",  icon: null },
        { id: "demo.canal",     name: "CANAL+",           icon: null },
        { id: "demo.tf1",       name: "TF1+",             icon: null },
        { id: "demo.m6",        name: "M6+",              icon: null },
        { id: "demo.arte",      name: "arte",             icon: null },
        { id: "demo.max",       name: "HBO Max",          icon: null },
        { id: "demo.music",     name: "Apple Music",      icon: null },
        { id: "demo.xbox",      name: "Xbox",             icon: null },
        { id: "TSLinkTV01.TizenSteamLink", name: "Tizen Steam Link", icon: null },
        { id: "MoonLightS.MoonlightWasm",  name: "Moonlight",        icon: null },
        { id: "demo.ligue1",    name: "Ligue 1+",         icon: null },
        { id: "com.samsung.tv.store", name: "Apps", icon: null },
        { id: "vetrotvapp.ui",  name: "Vetro",            icon: null }
    ];

    function hasTizen() {
        return typeof global.tizen !== "undefined" &&
               global.tizen.application &&
               typeof global.tizen.application.getAppsInfo === "function";
    }

    /* Images: on the screen, or on GitHub if they come from an update (boot.js) */
    function asset(p) { return p && global.APL_ASSET ? global.APL_ASSET(p) : p; }

    function decorate(app) {
        var m = lookup(app.id, app.name);
        return {
            id: app.id,
            name: m.name || app.name || app.id,
            icon: app.icon || null,
            accent: m.accent || app.accent || null,
            eyebrow: global.APL.t(m.eyebrow || "APP"),
            bg: asset(m.bg) || null,          // full-frame picture for the top shelf
            tile: asset(m.tile) || null,
            key: m.key || null,
            bgBlur: asset(m.bgBlur || (m.key ? "images/blur/" + m.key + ".jpg" : null)),   // pre-blurred background (grid)               // catalogue key (netflix, primevideo…)
            live: m.live || null,             // "youtube" for TizenTube             // full-frame artwork of the tile (like tvOS icons)
            favorite: FAVORITES.indexOf(app.id) !== -1 || isTizenTube(app.id, app.name)
        };
    }

    /* Favourites first (in declared order), then the rest alphabetically. */
    function order(apps) {
        var favRank = {};
        FAVORITES.forEach(function (id, i) { favRank[id] = i; });
        apps.forEach(function (a) { if (a.name === "TizenTube") favRank[a.id] = -1; });   // TizenTube first
        return apps.slice().sort(function (a, b) {
            var fa = (a.id in favRank), fb = (b.id in favRank);
            if (fa && fb) return favRank[a.id] - favRank[b.id];
            if (fa) return -1;
            if (fb) return 1;
            return a.name.localeCompare(b.name, global.APL.locale, { sensitivity: "base" });
        });
    }

    /* A single App Store tile: the screen sometimes lists two entries for the Samsung
       store (the store and the old Apps panel). com.samsung.tv.store is kept. */
    function dedupe(apps) {
        var stores = apps.filter(function (a) { return STORE_ID.test(a.id); });
        if (stores.length < 2) return apps;
        var keep = stores.filter(function (a) { return a.id === "com.samsung.tv.store"; })[0] || stores[0];
        return apps.filter(function (a) { return !STORE_ID.test(a.id) || a === keep; });
    }

    function loadApps() {
        return new Promise(function (resolve) {
            if (!hasTizen()) {
                resolve(order(DEMO_APPS.map(decorate)));
                return;
            }
            try {
                global.tizen.application.getAppsInfo(function (list) {
                    var apps = [];
                    for (var i = 0; i < list.length; i++) {
                        var a = list[i];
                        // `show:true` == meant to appear in the real Samsung menu.
                        // This is what strips the ~250 internal services.
                        if (!a.show) continue;
                        if (BLOCKLIST[a.id]) continue;
                        if (!isRealApp(a.id, a.name)) continue;
                        apps.push(decorate({ id: a.id, name: a.name, icon: a.iconPath }));
                    }
                    if (!apps.length) { resolve(order(DEMO_APPS.map(decorate))); return; }
                    // Overscan takes the place of Samsung Internet
                    overscanInstalled = apps.some(function (a) { return a.id === OVERSCAN; });
                    if (overscanInstalled) apps = apps.filter(function (a) { return !/^org\.tizen\.browser/.test(a.id); });
                    resolve(order(dedupe(apps)));
                }, function () {
                    resolve(order(DEMO_APPS.map(decorate)));
                });
            } catch (e) {
                resolve(order(DEMO_APPS.map(decorate)));
            }
        });
    }

    /* Websites added as apps (they open in Internet). The list is
       personal: "webApps" in js/keys.local.js (never published), filled in
       by APL Launcher Setup. E.g.: webApps: [{ name: "My site", url: "https://example.com/" }] */
    function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

    var overscanInstalled = false;
    /* Overscan receives no address at launch: it reads the page to start on from its settings
       file. We write it there (without changing the file's owner), then restart it.
       Already open on that site: it resumes as it was, video included. */
    var OVERSCAN_SETTINGS = "/opt/usr/home/owner/apps_rw/" + OVERSCAN + "/data/settings.tsv";
    var overscanUrl = null;
    function openInOverscan(url) {
        if (!/^https?:\/\/[^\s'"\\]+$/.test(url)) return Promise.reject(new Error(global.APL.t("Invalid address")));
        return global.APL.sys.runningApps().then(function (ids) {
            if (overscanUrl === url && ids.indexOf(OVERSCAN) !== -1) return launchApp(OVERSCAN);
            overscanUrl = url;
            var F = OVERSCAN_SETTINGS;
            var cmd = "app_launcher -k " + OVERSCAN + " >/dev/null 2>&1; " +
                "touch '" + F + "'; chown owner:system_share '" + F + "'; chsmack -a 'User::Pkg::" + OVERSCAN + "' '" + F + "'; " +
                "{ grep -vE '^(startup|hints)' '" + F + "'; echo 'hints\t0'; echo 'startupMode\turl'; echo 'startupUrl\t" + url + "'; } > /tmp/apl-overscan.tsv; " +
                "cat /tmp/apl-overscan.tsv > '" + F + "'; rm -f /tmp/apl-overscan.tsv; app_launcher -s " + OVERSCAN + " >/dev/null 2>&1; true";
            return global.APL.sys.exec(cmd).then(function () {});
        });
    }

    function openUrl(url) {
        if (overscanInstalled) return openInOverscan(url);
        return new Promise(function (resolve, reject) {
            if (!hasTizen() || !global.tizen.ApplicationControl || !global.tizen.application.launchAppControl) {
                reject(new Error(global.APL.t("PC preview: would open {url} in Internet", { url: url })));
                return;
            }
            var ctl = new global.tizen.ApplicationControl("http://tizen.org/appcontrol/operation/view", url, null, null, null);
            global.tizen.application.launchAppControl(ctl, "org.tizen.browser", function () { resolve(); }, function () {
                // Fallback: the browser chosen by the screen
                global.tizen.application.launchAppControl(ctl, null, function () { resolve(); },
                    function (e) { reject(new Error((e && e.message) || global.APL.t("Can't open Internet"))); });
            });
        });
    }

    function webApps() {
        var list = (global.APL_KEYS && global.APL_KEYS.webApps) || [];
        return list.filter(function (w) { return w && w.name && /^https?:\/\//.test(w.url || ""); }).map(function (w) {
            var a = decorate({ id: "web." + slug(w.name), name: w.name, icon: null });
            a.virtual = true; a.web = true; a.url = w.url; a.live = w.live || a.live;
            a.run = function () {
                openUrl(w.url).catch(function (e) { if (global.APL.toast) global.APL.toast(e.message); });
            };
            return a;
        });
    }

    function launchApp(id) {
        return new Promise(function (resolve, reject) {
            if (!hasTizen() || typeof global.tizen.application.launch !== "function") {
                reject(new Error(global.APL.t("PC preview: launch unavailable ({id})", { id: id })));
                return;
            }
            function plain() {
                global.tizen.application.launch(id, function () { resolve(); },
                    function (e) { reject(new Error((e && e.message) || global.APL.t("Can't launch the app"))); });
            }
            // Already open: it comes back as it was. Without SkipReload, the screen reloads
            // the whole web app (and TizenTube starts over from scratch through TizenBrew).
            global.APL.sys.runningApps().then(function (ids) {
                if (ids.indexOf(id) === -1) { plain(); return; }
                resumeApp(id, resolve, plain);
            }, plain);
        });
    }
    function resumeApp(id, ok, failed) {
        try {
            var T = global.tizen;
            var ctl = new T.ApplicationControl("http://tizen.org/appcontrol/operation/default", null, null, null,
                                               [new T.ApplicationControlData("SkipReload", ["Yes"])]);
            T.application.launchAppControl(ctl, id, function () { ok(); }, failed);
        } catch (e) { failed(); }
    }

    /* TizenTube without going through TizenBrew's screen. If it is already running, it comes back as it
       was, video included. Otherwise TizenBrew starts, restarts itself in debug mode (the screen briefly
       goes back through Samsung's home), then waits for the module to be chosen: the screen makes that
       choice itself (the launcher, in the background, can no longer do anything at that point). */
    var BREW = "xvvl3S1bvH.TizenBrewStandalone";
    function tubeWatcher() {
        return "(n=0; seen=0; while [ $n -lt 40 ]; do sleep 1; n=$((n+1)); " +
            "a=$(vconftool get memory/appfw/current_fullscreen_appid 2>/dev/null); " +
            "case \"$a\" in " +
            "*csfs*|*home.sidebar*) seen=1; app_launcher -s " + MY_APP_ID + ";; " +
            "*TizenBrew*) if [ $seen = 1 ] || [ $n -ge 12 ]; then sleep 4; input_keyevent Down; sleep 1; input_keyevent Return; break; fi;; " +
            "esac; done) >/dev/null 2>&1 &";
    }
    function launchTizenTube() {
        return global.APL.sys.runningApps().then(function (ids) {
            if (ids.indexOf(BREW) !== -1) return launchApp(BREW);
            global.APL.holdVeil(24000);
            return global.APL.sys.exec(tubeWatcher()).then(function () { return launchApp(BREW); }, function () { return launchApp(BREW); });
        });
    }

    /* Is the app still installed? (checks an uninstall done through Vetro) */
    function isInstalled(id) {
        return new Promise(function (resolve) {
            if (!hasTizen()) { resolve(false); return; }
            try {
                global.tizen.application.getAppsInfo(function (list) {
                    for (var i = 0; i < list.length; i++) if (list[i].id === id) { resolve(true); return; }
                    resolve(false);
                }, function () { resolve(true); });
            } catch (e) { resolve(true); }
        });
    }

    global.APL = global.APL || {};
    global.APL.loadApps = loadApps;
    global.APL.isInstalled = isInstalled;
    global.APL.webApps = webApps;
    global.APL.openUrl = openUrl;
    global.APL.launchApp = launchApp;
    global.APL.launchTizenTube = launchTizenTube;
    global.APL.TIZENTUBE_ART = { tile: asset(TIZENTUBE.tile), bg: asset(TIZENTUBE.bg), bgBlur: asset(TIZENTUBE.bgBlur) };
    global.APL.FAVORITES = FAVORITES;

})(window);
